export function thought(r: RngHolder, key: string, vars: Record<string, string> = {}) {
  const list = THOUGHTS[key];
  if (!list) return "";
  let s = pick(r, list);
  for (const [k, v] of Object.entries(vars)) {
    s = s.replace(`{${k}}이(가)`, josa(v, "이/가")).replace(`{${k}}와(과)`, josa(v, "과/와")).replace(`{${k}}을(를)`, josa(v, "을/를")).replaceAll(`{${k}}`, v);
  }
  return s;
}

