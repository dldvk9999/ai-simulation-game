/** 이름이 다 쓰이면 두 글자를 새로 지어 붙인다 */
const SYL_A = ["가", "나", "다", "라", "마", "바", "사", "아", "자", "하", "서", "도", "유", "지", "소", "은", "태", "해", "윤", "재"];
